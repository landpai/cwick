    "        uint2 gid [[threadgroup_position_in_grid]],\n"
    "        ushort lane [[thread_index_in_simdgroup]],\n"
    "        ushort sg [[simdgroup_index_in_threadgroup]]) {\n"
    /* One simdgroup owns one row and the 32 lanes split its blocks: block b is
     * a self-contained sum, so the lanes need no order among themselves. Only
     * the final `acc +=` chain is ordered, and that is 160 adds on one lane
     * against 5120 multiply-adds per row.
     *
     * The first version gave a whole row to a single thread. That is the same
     * arithmetic and 32x fewer threads -- a [2304, 5120] matrix then had 2304
     * threads in flight, which is one warp per GPU core, and it measured
     * 8 GB/s. Spreading the blocks over the lanes is what puts the memory
     * system to work. */
    "    uint row = args.row0 + gid.x * (uint)args.nsg + (uint)sg;\n"
    "    uint nb = args.nb;\n"
    "    threadgroup float lut[16];\n"
    "    threadgroup float *mine = tmp + (ulong)sg * args.nbmax;\n"
    "    cwick_ds_e2m1_build(lut, sg, lane);\n"
    "    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
    "    if (row < args.n) {\n"
    "        device const uchar *base = (device const uchar *)w + (ulong)row * (args.k >> 1u);\n"
    "        device const uchar *rs = ws + (ulong)row * nb;\n"
    "        for (uint b = (uint)lane; b < nb; b += 32u) {\n"
    "            /* One 16-byte load per lane, not four 4-byte ones: with 32 lanes\n"
    "             * holding 32 consecutive blocks, a scalar load reads 4 bytes out\n"
    "             * of each 16 and needs three more instructions to reach the\n"
    "             * rest, and those three were measured re-fetching DRAM rather\n"
    "             * than hitting in L1 -- 4x the traffic for the same bytes. */\n"
    "            uint4 v = *(device const uint4 *)(base + (ulong)b * 16u);\n"
    "            device const float *ap = af + b * 32u;\n"
    "            /* The 32 activation values this lane needs are 128 bytes of\n"
    "             * L1, but the 32 lanes want 32 *different* 128-byte stretches,\n"
    "             * so each scalar read is its own sector fetch. Eight vector\n"
    "             * loads instead of thirty-two scalar ones is the difference\n"
    "             * between 38 and 150 GB/s here. */\n"
    "            float4 q0 = *(device const float4 *)(ap + 0u);\n"
    "            float4 q1 = *(device const float4 *)(ap + 4u);\n"
    "            float4 q2 = *(device const float4 *)(ap + 8u);\n"
    "            float4 q3 = *(device const float4 *)(ap + 12u);\n"
    "            float4 q4 = *(device const float4 *)(ap + 16u);\n"
    "            float4 q5 = *(device const float4 *)(ap + 20u);\n"
    "            float4 q6 = *(device const float4 *)(ap + 24u);\n"
    "            float4 q7 = *(device const float4 *)(ap + 28u);\n"
    "            float a[32] = { q0.x, q0.y, q0.z, q0.w, q1.x, q1.y, q1.z, q1.w,\n"
    "                            q2.x, q2.y, q2.z, q2.w, q3.x, q3.y, q3.z, q3.w,\n"
    "                            q4.x, q4.y, q4.z, q4.w, q5.x, q5.y, q5.z, q5.w,\n"
    "                            q6.x, q6.y, q6.z, q6.w, q7.x, q7.y, q7.z, q7.w };\n"
    "            uint w0 = v.x, w1 = v.y, w2 = v.z, w3 = v.w;\n"
    "            float s00 = CWICK_DS_PAIR(w0, 0, a[0],  a[1]);\n"
    "            float s01 = CWICK_DS_PAIR(w0, 1, a[2],  a[3]);\n"
    "            float s02 = CWICK_DS_PAIR(w0, 2, a[4],  a[5]);\n"
    "            float s03 = CWICK_DS_PAIR(w0, 3, a[6],  a[7]);\n"
    "            float s10 = CWICK_DS_PAIR(w1, 0, a[8],  a[9]);\n"
    "            float s11 = CWICK_DS_PAIR(w1, 1, a[10], a[11]);\n"
    "            float s12 = CWICK_DS_PAIR(w1, 2, a[12], a[13]);\n"
    "            float s13 = CWICK_DS_PAIR(w1, 3, a[14], a[15]);\n"
    "            float s20 = CWICK_DS_PAIR(w2, 0, a[16], a[17]);\n"
    "            float s21 = CWICK_DS_PAIR(w2, 1, a[18], a[19]);\n"
    "            float s22 = CWICK_DS_PAIR(w2, 2, a[20], a[21]);\n"
    "            float s23 = CWICK_DS_PAIR(w2, 3, a[22], a[23]);\n"
    "            float s30 = CWICK_DS_PAIR(w3, 0, a[24], a[25]);\n"
    "            float s31 = CWICK_DS_PAIR(w3, 1, a[26], a[27]);\n"
    "            float s32 = CWICK_DS_PAIR(w3, 2, a[28], a[29]);\n"
    "            float s33 = CWICK_DS_PAIR(w3, 3, a[30], a[31]);\n"
    "            float t0 = (s00 + s10) + (s20 + s30);\n"
    "            float t1 = (s01 + s11) + (s21 + s31);\n"
    "            float t2 = (s02 + s12) + (s22 + s32);\n"
    "            float t3 = (s03 + s13) + (s23 + s33);\n"
    "            float part = (t0 + t1) + (t2 + t3);\n"
    "            mine[b] = (part * asf[b]) * cwick_ds_e8m0(rs[b]);\n"
    "        }\n"
    "    }\n"
    "    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
    "    if (row < args.n && lane == 0) {\n"
    "        float acc = 0.0f;\n"
    "        for (uint b = 0; b < nb; b++) acc += mine[b];\n"
    "        out[row - args.row0] = acc;\n"
    "    }\n"
    "}\n"
    "kernel void kernel_cwick_ds_bf16_gemv(\n"
    "        constant cwick_ds_gemv_args &args,\n"
    "        device const uint  *w,      // [n][k] bf16 pairs\n"
    "        device const uchar *ws,     // [n/32][nb] e8m0\n"
    "        device const float *af,\n"
    "        device const float *asf,\n"
    "        device float       *out,\n"
    "        threadgroup float  *tmp,\n"
    "        uint2 gid [[threadgroup_position_in_grid]],\n"
    "        ushort lane [[thread_index_in_simdgroup]],\n"
    "        ushort sg [[simdgroup_index_in_threadgroup]]) {\n"
    "    uint row = args.row0 + gid.x * (uint)args.nsg + (uint)sg;\n"
    "    uint nb = args.nb;\n"
    "    threadgroup float *mine = tmp + (ulong)sg * args.nbmax;\n"
    "    if (row < args.n) {\n"
    "        device const uint *base = w + (ulong)row * (args.k >> 1u);\n"
    "        device const uchar *rs = ws + ((ulong)(row >> 5u)) * nb;\n"
    "        for (uint b = (uint)lane; b < nb; b += 32u) {\n"
    "            device const uint4 *p = (device const uint4 *)((device const uchar *)base + (ulong)b * 64u);\n"
    "            device const float *a = af + b * 32u;\n"
    "            uint4 q0 = p[0], q1 = p[1], q2 = p[2], q3 = p[3];\n"
    "            uint u0 = q0.x, u1 = q0.y, u2 = q0.z, u3 = q0.w;\n"
    "            uint u4 = q1.x, u5 = q1.y, u6 = q1.z, u7 = q1.w;\n"
    "            uint u8 = q2.x, u9 = q2.y, uA = q2.z, uB = q2.w;\n"
    "            uint uC = q3.x, uD = q3.y, uE = q3.z, uF = q3.w;\n"
    "            float s0x = cwick_bf16_to_f32((ushort)(u0 & 0xffffu)) * a[0];\n"
    "            float s0y = cwick_bf16_to_f32((ushort)(u0 >> 16u)) * a[1];\n"
    "            float s0z = cwick_bf16_to_f32((ushort)(u1 & 0xffffu)) * a[2];\n"
    "            float s0w = cwick_bf16_to_f32((ushort)(u1 >> 16u)) * a[3];\n"
    "            float s1x = cwick_bf16_to_f32((ushort)(u2 & 0xffffu)) * a[4];\n"
    "            float s1y = cwick_bf16_to_f32((ushort)(u2 >> 16u)) * a[5];\n"
    "            float s1z = cwick_bf16_to_f32((ushort)(u3 & 0xffffu)) * a[6];\n"
    "            float s1w = cwick_bf16_to_f32((ushort)(u3 >> 16u)) * a[7];\n"
    "            float s2x = cwick_bf16_to_f32((ushort)(u4 & 0xffffu)) * a[8];\n"
    "            float s2y = cwick_bf16_to_f32((ushort)(u4 >> 16u)) * a[9];\n"
    "            float s2z = cwick_bf16_to_f32((ushort)(u5 & 0xffffu)) * a[10];\n"
    "            float s2w = cwick_bf16_to_f32((ushort)(u5 >> 16u)) * a[11];\n"
    "            float s3x = cwick_bf16_to_f32((ushort)(u6 & 0xffffu)) * a[12];\n"
    "            float s3y = cwick_bf16_to_f32((ushort)(u6 >> 16u)) * a[13];\n"
    "            float s3z = cwick_bf16_to_f32((ushort)(u7 & 0xffffu)) * a[14];\n"
    "            float s3w = cwick_bf16_to_f32((ushort)(u7 >> 16u)) * a[15];\n"
    /* the reference narrows to four lanes and combines them pairwise, so the
     * second half of the block folds into the same four accumulators */
    "            s0x += cwick_bf16_to_f32((ushort)(u8 & 0xffffu)) * a[16];\n"
    "            s0y += cwick_bf16_to_f32((ushort)(u8 >> 16u)) * a[17];\n"
    "            s0z += cwick_bf16_to_f32((ushort)(u9 & 0xffffu)) * a[18];\n"
    "            s0w += cwick_bf16_to_f32((ushort)(u9 >> 16u)) * a[19];\n"
    "            s1x += cwick_bf16_to_f32((ushort)(uA & 0xffffu)) * a[20];\n"
    "            s1y += cwick_bf16_to_f32((ushort)(uA >> 16u)) * a[21];\n"
    "            s1z += cwick_bf16_to_f32((ushort)(uB & 0xffffu)) * a[22];\n"
    "            s1w += cwick_bf16_to_f32((ushort)(uB >> 16u)) * a[23];\n"
    "            s2x += cwick_bf16_to_f32((ushort)(uC & 0xffffu)) * a[24];\n"
    "            s2y += cwick_bf16_to_f32((ushort)(uC >> 16u)) * a[25];\n"
    "            s2z += cwick_bf16_to_f32((ushort)(uD & 0xffffu)) * a[26];\n"
    "            s2w += cwick_bf16_to_f32((ushort)(uD >> 16u)) * a[27];\n"
    "            s3x += cwick_bf16_to_f32((ushort)(uE & 0xffffu)) * a[28];\n"
    "            s3y += cwick_bf16_to_f32((ushort)(uE >> 16u)) * a[29];\n"
    "            s3z += cwick_bf16_to_f32((ushort)(uF & 0xffffu)) * a[30];\n"
    "            s3w += cwick_bf16_to_f32((ushort)(uF >> 16u)) * a[31];\n"
    "            float t0 = (s0x + s1x) + (s2x + s3x);\n"
    "            float t1 = (s0y + s1y) + (s2y + s3y);\n"
    "            float t2 = (s0z + s1z) + (s2z + s3z);\n"
    "            float t3 = (s0w + s1w) + (s2w + s3w);\n"
    "            float part = (t0 + t1) + (t2 + t3);\n"
    "            mine[b] = (part * asf[b]) * cwick_ds_e8m0(rs[b]);\n"
    "        }\n"
    "    }\n"
    "    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
    "    if (row < args.n && lane == 0) {\n"
    "        float acc = 0.0f;\n"
    "        for (uint b = 0; b < nb; b++) acc += mine[b];\n"
    "        out[row - args.row0] = acc;\n"
    "    }\n"
    "}\n";
